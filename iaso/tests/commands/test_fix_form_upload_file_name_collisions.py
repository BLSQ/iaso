    def test_apply_logs_the_values_before_and_after_by_the_given_user(self):
        self.collide_second_phone_uploads_after_first()
        belgium_before = m.Instance.objects.get(uuid=BELGIUM_UUID)

        self.call_command("--apply", "--username", self.belgium_user.username)

        belgium_after = m.Instance.objects.get(uuid=BELGIUM_UUID)
        repair_log = Modification.objects.get(source=REPAIR_SOURCE, object_id=str(belgium_after.id))
        self.assertEqual(repair_log.user, self.belgium_user)
        self.assertEqual(
            [
                {key: value["fields"][key] for key in ("file", "created_by", "last_modified_by")}
                for value in repair_log.past_value + repair_log.new_value
            ],
            [
                {
                    "file": belgium_before.file.name,
                    "created_by": self.france_user.id,
                    "last_modified_by": self.france_user.id,
                },
                {
                    "file": belgium_after.file.name,
                    "created_by": self.belgium_user.id,
                    "last_modified_by": self.belgium_user.id,
                },
            ],
        )
        self.assertEqual(repair_log.past_value[0]["fields"]["json"]["instanceID"], BELGIUM_XML_ID)
        self.assertEqual(repair_log.new_value[0]["fields"]["json"]["instanceID"], BELGIUM_XML_ID)

    def test_apply_uploads_a_backup_of_the_instances_before_changing_them(self):
        self.collide_second_phone_uploads_after_first()
        before = {
            instance.id: (instance.file.name or None, instance.created_by_id, instance.json)
            for instance in m.Instance.objects.all()
        }

        out = self.call_command("--apply")

        backup_key = re.search(r"^BACKUP (\S+)$", out, re.MULTILINE).group(1)
        self.assertTrue(backup_key.startswith(f"{BACKUP_PREFIX}/backup_"))
        storage = m.Instance._meta.get_field("file").storage
        with storage.open(backup_key, "rb") as backup, zipfile.ZipFile(backup) as backup_zip:
            backed_up = {
                obj.object.id: (obj.object.file.name or None, obj.object.created_by_id, obj.object.json)
                for obj in serializers.deserialize("json", backup_zip.read("instances.json"))
            }
            plan = json.loads(backup_zip.read("plan.json"))
        self.assertEqual(backed_up, before)
        self.assertCountEqual([repair["instance_id"] for repair in plan], before.keys())

