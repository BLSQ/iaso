    def collide_second_phone_uploads_after_first(self):
        """Most common prod case (e.g. instance 9570993)."""
        self.post_instance(self.belgium_user, BELGIUM_UUID, self.belgium)
        self.upload_xml(self.belgium_user, BELGIUM_XML_ID)
        self.post_instance(self.france_user, FRANCE_UUID, self.france)
        self.upload_xml(self.france_user, FRANCE_XML_ID)

    def test_reproduces_the_mix_up(self):
        self.collide_second_phone_uploads_after_first()
        self.report_instances("After the uploads of both phones")

        dup_file_name = f"{FILE_NAME[:-4]}_dup_{FRANCE_UUID}.xml"
        self.assertEqual(
            self.instance_state(BELGIUM_UUID),
            {
                **self.expected_state(BELGIUM_UUID, FILE_NAME, self.belgium, self.belgium_user, BELGIUM_XML_ID),
                # the france xml and user, but still the json (and device) of the belgium xml
                "created_by": "france_user",
                "last_modified_by": "france_user",
                "file_size": len(submission_xml(FRANCE_XML_ID, "france_user")),
                "file_instance_id": FRANCE_XML_ID,
            },
        )
        self.assertEqual(
            self.instance_state(FRANCE_UUID),
            {
                **self.expected_state(FRANCE_UUID, dup_file_name, self.france, self.france_user, FRANCE_XML_ID),
                # never received its xml
                "form_version": None,
                "created_by": None,
                "last_modified_by": None,
                "json_instance_id": None,
                "json_user_name": None,
                "device": None,
                "file_size": None,
                "file_instance_id": None,
            },
        )

    def test_dry_run_changes_nothing(self):
        self.collide_second_phone_uploads_after_first()
        before = [self.instance_state(BELGIUM_UUID), self.instance_state(FRANCE_UUID)]

        out = self.call_command()

        self.assertIn("1 groups: 1 to repair, 0 already fine, 0 skipped", out)
        self.assertEqual(out.count("WOULD REPAIR instance"), 2)
        self.assertEqual([self.instance_state(BELGIUM_UUID), self.instance_state(FRANCE_UUID)], before)
        self.assertFalse(Modification.objects.filter(source=REPAIR_SOURCE).exists())
        self.assertNotIn("BACKUP", out)

